#!/usr/bin/env python3
"""Bake Kodak film-preview tone tables. Run with --check to verify the committed Swift data."""
import argparse
import base64
import math
from pathlib import Path
import struct
import textwrap

# Density samples at 0.25 log10(lux-second) intervals, in RGB or diffuse visual order.
# Sources, viewing assumptions and graph references are documented in docs/film-look-profiles.md.
PROFILES = {
    "portra400": (-3.25, -1.44, [
        (0.22, .65, .87), (.23, .66, .89), (.26, .69, .96), (.34, .78, 1.10),
        (.47, .91, 1.25), (.59, 1.05, 1.41), (.72, 1.19, 1.57), (.86, 1.33, 1.72),
        (.99, 1.47, 1.88), (1.13, 1.61, 2.04), (1.27, 1.74, 2.20), (1.41, 1.88, 2.36),
        (1.55, 2.02, 2.52), (1.69, 2.15, 2.69), (1.83, 2.29, 2.85), (1.98, 2.43, 3.01),
    ]),
    "ektar100": (-2.75, -.84, [
        (.21, .64, .86), (.22, .64, .87), (.24, .66, .91), (.30, .72, 1.02),
        (.41, .84, 1.17), (.53, .99, 1.34), (.67, 1.13, 1.51), (.83, 1.28, 1.67),
        (.98, 1.43, 1.83), (1.12, 1.57, 2.00), (1.26, 1.72, 2.17), (1.40, 1.85, 2.34),
        (1.53, 1.98, 2.49), (1.65, 2.10, 2.64), (1.77, 2.22, 2.78), (1.87, 2.34, 2.95),
    ]),
    "ektachromeE100": (-2.75, -.84, [
        (3.24, 3.60, 3.75), (3.21, 3.55, 3.67), (3.08, 3.39, 3.46), (2.81, 3.05, 3.04),
        (2.38, 2.54, 2.47), (1.86, 1.96, 1.87), (1.38, 1.43, 1.35), (.98, 1.01, .95),
        (.67, .68, .63), (.43, .43, .39), (.26, .26, .23), (.16, .16, .15),
    ]),
    # 400TX 35 mm, D-76, large tank, 20 °C, eight minutes.
    "triX400": (-3.25, -1.44, [(d, d, d) for d in
        (.30, .31, .36, .45, .57, .71, .86, 1.01, 1.17, 1.34, 1.50, 1.65, 1.80, 1.93, 2.05)]),
}


def density_at(samples, start, exposure, channel):
    position = min(len(samples) - 1, max(0, (exposure - start) / .25))
    index = int(position)
    a = samples[index][channel]
    b = samples[min(index + 1, len(samples) - 1)][channel]
    return a + (position - index) * (b - a)


def table_for(name):
    start, reference, samples = PROFILES[name]
    table = bytearray()
    for index in range(257):
        # CIColorCurves interpolates in encoded sRGB, giving the toe more table entries.
        code = index / 256
        linear = code / 12.92 if code <= .04045 else ((code + .055) / 1.055) ** 2.4
        exposure = reference + math.log10(linear / .18) if linear else start
        for channel in range(3):
            density = density_at(samples, start, exposure, channel)
            middle = density_at(samples, start, reference, channel)
            if name == "ektachromeE100":
                output = .18 * 10 ** (middle - density)
            else:
                # A common virtual print contrast and base subtraction make the negative viewable.
                base = samples[0][channel]
                output = .18 * (10 ** (1.65 * (density - base)) - 1) / (10 ** (1.65 * (middle - base)) - 1)
            if output > .75:
                output = 1 - .25 * math.exp(-((output - .75) / .25))
            encoded = 12.92 * output if output <= .0031308 else 1.055 * output ** (1 / 2.4) - .055
            table.extend(struct.pack("<f", encoded))
    return table


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    destination = Path(__file__).resolve().parents[1] / "FFFilm" / "KodakFilmLookTables.swift"
    lines = ["// Generated by script/generate_film_look_tables.py from published density curves.",
             "// Each table contains 257 interleaved Float32 RGB triplets in sRGB.",
             "#if os(iOS)", "import Foundation", "", "nonisolated enum KodakFilmLookTables {"]
    for name in PROFILES:
        encoded = base64.b64encode(table_for(name)).decode("ascii")
        lines.append(f'    static let {name} = Data(base64Encoded: """')
        lines.extend("        " + part for part in textwrap.wrap(encoded, 96))
        lines.append('        """, options: .ignoreUnknownCharacters)!')
    generated = "\n".join(lines + ["}", "#endif", ""])
    if args.check:
        if destination.read_text() != generated:
            raise SystemExit("Regenerate KodakFilmLookTables.swift with script/generate_film_look_tables.py")
    else:
        destination.write_text(generated)


if __name__ == "__main__":
    main()
